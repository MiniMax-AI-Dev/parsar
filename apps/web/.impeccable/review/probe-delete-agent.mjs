import { chromium } from "@playwright/test"
const EXE = `${process.env.HOME}/.cache/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-linux64/chrome-headless-shell`
const browser = await chromium.launch({ executablePath: EXE, args:["--no-sandbox","--disable-gpu"] })
const ctx = await browser.newContext({ viewport:{width:1440,height:900}, locale:"zh-CN", extraHTTPHeaders:{ "X-Parsar-Dev-User-ID": process.env.DEV_USER } })
await ctx.addInitScript((ws)=>{localStorage.setItem("parsar.theme","light");localStorage.setItem("parsar.lang","zh-CN");localStorage.setItem("parsar.ws",ws)},process.env.WS)
const page = await ctx.newPage()
const calls=[]
page.on("response", r => { const m=r.request().method(); if (r.url().includes("/api/") && (m!=="GET"||r.status()>=400)) calls.push(`${r.status()} ${m} ${r.url().split("/api/v1")[1]}`) })
page.on("pageerror", e => console.log("  PAGEERROR", e.message.slice(0,160)))
await page.goto("http://127.0.0.1:5173/?admin=agents",{waitUntil:"load"}); await page.waitForTimeout(2500)
const before = await page.locator('[role="option"]').count()
const row = page.locator('[role="option"]').first()
const name = (await row.innerText()).split("\n")[0].trim()
console.log("rows before:", before, "deleting:", name)
await row.hover(); await page.waitForTimeout(400)
await row.getByRole("button", { name: "更多操作" }).click(); await page.waitForTimeout(800)
await page.getByRole("menuitem", { name: /删除/ }).first().click(); await page.waitForTimeout(1000)
const dlg = page.locator('[role="dialog"], [role="alertdialog"]').first()
const text = await dlg.innerText()
const token = text.match(/[「『]([^」』]{2,60})[」』]/)?.[1] ?? ""
console.log("confirm token:", JSON.stringify(token))
const confirm = dlg.getByRole("button", { name: /删除 Agent|删除|确认/ }).last()
console.log("confirm enabled before typing:", await confirm.isEnabled())
await dlg.locator("input").first().fill(token); await page.waitForTimeout(500)
console.log("confirm enabled after typing:", await confirm.isEnabled())
await confirm.click(); await page.waitForTimeout(2500)
console.log("dialog still open:", await page.locator('[role="dialog"], [role="alertdialog"]').count())
console.log("rows after:", await page.locator('[role="option"]').count())
console.log("calls:", calls.join(" | ") || "(none)")
await page.screenshot({ path: ".impeccable/review/crawl/agents-after-delete.png" })
await browser.close()
